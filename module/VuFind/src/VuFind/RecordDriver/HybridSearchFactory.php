namespace VuFind\RecordDriver;

use Psr\Container\ContainerInterface;

/**
 * Factory for HybridSearch record drivers.
 *
 * @category VuFind
 * @package  RecordDrivers
 * @author   Jesiel Viana <jesielviana@gmail.com>
 * @license  http://opensource.org/licenses/gpl-2.0.php GNU General Public License
 * @link     https://vufind.org/wiki/development Wiki
 */
class HybridSearchFactory extends AbstractBaseFactory
{
    /**
     * Create an object
     *
     * @param ContainerInterface $container     Service manager
     * @param string             $requestedName Service being created
     * @param null|array         $options       Extra options (optional)
     *
     * @return object
     */
    public function __invoke(
        ContainerInterface $container,
        $requestedName,
        ?array $options = null
    ) {
        if (!empty($options)) {
            throw new \Exception('Unexpected options passed to factory.');
        }
        $config = $container->get(\VuFind\Config\ConfigManagerInterface::class)->getConfigObject('searches');
        $finalOptions = [null, $config];
        return parent::__invoke($container, $requestedName, $finalOptions);
    }
}
